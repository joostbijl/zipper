#!/usr/bin/env bash
# Install two Finder Quick Actions (Automator workflows) into
# ~/Library/Services so they appear in Finder's right-click menu:
#   "Add to Zipper Archive"  — selected files → new archive window (⌘S to save)
#   "Open in Zipper"         — selected archives/images → open in Zipper
# They just call `open -a Zipper`, so they keep working across app updates.
#
#   scripts/quick-actions.sh            # install
#   scripts/quick-actions.sh --remove
set -euo pipefail

SERVICES="$HOME/Library/Services"
NAMES=("Add to Zipper Archive" "Open in Zipper")

if [[ "${1:-}" == "--remove" ]]; then
  for n in "${NAMES[@]}"; do rm -rf "$SERVICES/$n.workflow"; done
  /System/Library/CoreServices/pbs -update >/dev/null 2>&1 || true
  echo "removed"
  exit 0
fi

